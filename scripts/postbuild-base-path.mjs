// Post-build clean-up of the generated HTML in dist/:
// 1. Removes internal "<!-- OPEN: … -->" notes from Markdown/templates so they never reach the public.
// 2. For the preview at https://<user>.github.io/<repo>/ (BASE_PATH set), prefixes root-relative
//    links from Markdown content ("/downloads/…") with the base path. Components already do this.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const base = (process.env.BASE_PATH || '/').replace(/\/$/, '');
const esc = base.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const linkRe = base ? new RegExp(`(href|src)="/(?!/|${esc.slice(1)}/)`, 'g') : null;
const openRe = /<!--\s*OPEN:[\s\S]*?-->/g;

async function* files(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) yield* files(p);
    else if (p.endsWith('.html')) yield p;
  }
}
let changed = 0;
for await (const f of files('dist')) {
  const html = await readFile(f, 'utf8');
  let out = html.replace(openRe, '');
  if (linkRe) out = out.replace(linkRe, `$1="${base}/`);
  if (out !== html) { await writeFile(f, out); changed++; }
}
console.log(`postbuild: cleaned ${changed} HTML files${base ? ` (base path ${base})` : ''}`);

// 3. For the live server (Apache/LiteSpeed on the Bantu e.V. hosting, HTACCESS=1):
//    write dist/.htaccess with HTTPS/www canonical host, real 301 redirects for the old
//    WordPress URLs, the 404 page, caching and basic security headers.
if (process.env.HTACCESS === '1') {
  const { wordpressRedirects, fileRedirects = {} } = await import('../src/data/redirects.mjs');
  const host = new URL(process.env.SITE_URL || 'https://www.bantu-ev.org').host;
  const apex = host.replace(/^www\./, '');
  const reEsc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const rules = Object.entries({ ...wordpressRedirects, ...fileRedirects }).map(([from, to]) =>
    `RewriteRule ^${reEsc(from.replace(/^\//, ''))}/?$ ${to.replace('#', '\\#')} [R=301,L,NE]`);
  const htaccess = `# Generated by scripts/postbuild-base-path.mjs – do not edit on the server.
# Bantu e.V. static website (Astro). Source: https://github.com/Nianetworks/bantu-e.v
Options -Indexes -MultiViews
ServerSignature Off
FileETag None
DirectoryIndex index.html
ErrorDocument 404 /404.html
AddDefaultCharset UTF-8
AddType image/webp .webp
AddType application/manifest+json .webmanifest
AddType video/mp4 .mp4
AddType text/vtt .vtt

<IfModule mod_rewrite.c>
RewriteEngine On
# Certificate validation (AutoSSL / Let's Encrypt) and security.txt must stay reachable
RewriteRule ^\\.well-known/ - [L]
# The one exception (shop order form, decision of the chair 08.11.2026): POST over HTTPS to exactly shop/bestellung.php.
# Any other method on that file falls through to the 405/404 rules below; no other script can run.
RewriteCond %{REQUEST_METHOD} =POST
RewriteCond %{HTTPS} =on [OR]
RewriteCond %{HTTP:X-Forwarded-Proto} =https
RewriteRule ^shop/bestellung\\.php$ - [END]
# Self-defence: otherwise this is a static site, so only reading is allowed (no uploads, no form posts to this server)
RewriteCond %{REQUEST_METHOD} !^(GET|HEAD|OPTIONS)$
RewriteRule ^ - [R=405,L]
# Never serve hidden files, backups, sources or config files
RewriteRule (^|/)\\.(?!well-known/) - [R=404,L]
RewriteRule \\.(bak|old|orig|save|swp|sql|sqlite|db|env|ini|log|sh|py|php[0-9]?|phtml|cgi|pl|asp|aspx|jsp|ya?ml|toml|lock|git)(/|$) - [R=404,L,NC]
# Typical attack probes (admin panels, shells, path traversal)
RewriteRule (^|/)(phpmyadmin|pma|myadmin|adminer|cgi-bin|vendor|node_modules|\\.git|\\.svn|\\.env|server-status|server-info)(/|$) - [R=404,L,NC]
RewriteCond %{QUERY_STRING} (\\.\\./|%2e%2e|<script|%3Cscript|union.*select|base64_encode|GLOBALS=|_REQUEST=|/etc/passwd) [NC]
RewriteRule ^ - [R=403,L]
# Canonical address: https://${host}
RewriteCond %{HTTP_HOST} ^${reEsc(apex)}$ [NC]
RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L,NE]
RewriteCond %{HTTPS} !=on
RewriteCond %{HTTP:X-Forwarded-Proto} !https
RewriteCond %{HTTP_HOST} ^${reEsc(host)}$ [NC]
RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L,NE]
# Old WordPress addresses -> new pages
${rules.join('\n')}
# Old WordPress feeds and system paths
RewriteRule ^feed/?$ /aktuelles/rss.xml [R=301,L]
RewriteRule ^(wp-admin|wp-login\\.php|xmlrpc\\.php|wp-json)(/.*)?$ - [R=410,L]
</IfModule>

<IfModule mod_headers.c>
Header always set X-Content-Type-Options "nosniff"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set X-Frame-Options "SAMEORIGIN"
Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(self \\"https://spenden.twingle.de\\"), usb=(), interest-cohort=()"
Header always set Strict-Transport-Security "max-age=31536000"
Header always set Cross-Origin-Opener-Policy "same-origin-allow-popups"
Header always set X-Permitted-Cross-Domain-Policies "none"
Header always set Content-Security-Policy "default-src 'self'; script-src 'self' 'unsafe-inline' https://*.twingle.de; style-src 'self' 'unsafe-inline' https://*.twingle.de; img-src 'self' data: https:; font-src 'self' data: https://*.twingle.de; connect-src 'self' https://*.twingle.de; frame-src https://*.twingle.de; form-action 'self' mailto: https://*.twingle.de; frame-ancestors 'self'; base-uri 'self'; object-src 'none'; upgrade-insecure-requests"
Header always unset X-Powered-By
<FilesMatch "\\.(html|xml)$">
Header set Cache-Control "no-cache"
</FilesMatch>
<FilesMatch "\\.(css|js|woff2?|webp|png|jpe?g|svg|ico|pdf|mp4)$">
Header set Cache-Control "public, max-age=2592000"
</FilesMatch>
</IfModule>
<IfModule mod_expires.c>
ExpiresActive On
ExpiresByType text/html "access plus 0 seconds"
</IfModule>
`;
  await writeFile('dist/.htaccess', htaccess);
  console.log(`postbuild: wrote dist/.htaccess (${rules.length} redirects, host ${host})`);
}
